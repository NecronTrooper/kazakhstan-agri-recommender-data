DESCRIPTIONS = {col: (unit, text, group, src)
                for group, src, cols in GROUPS for col, (unit, text) in cols.items()}


def fmt_range(s: pd.Series) -> str:
    if not pd.api.types.is_numeric_dtype(s) or s.dropna().empty:
        return f"{s.nunique()} знач."
    lo, hi = s.min(), s.max()
    if lo == hi:
        return f"{lo:g}"
    return f"{lo:.6g} … {hi:.6g}"


def main():
    d = pd.read_csv(DATA_PATH)
    missing = [c for c in d.columns if c not in DESCRIPTIONS]
    stale = [c for c in DESCRIPTIONS if c not in d.columns]
    if missing or stale:
        raise SystemExit(f"Словарь рассинхронизирован. Нет описания: {missing}; лишние описания: {stale}")

    lines = [
        "# Словарь данных: `output/master_dataset_districts.csv`",
        "",
        f"Генерируется скриптом `17_data_dictionary.py` (описания в нём, тип/пропуски/диапазон считаются из файла). "
        f"Актуально для сборки с данными по {int(d['year'].min())}–{int(d['year'].max())} годам.",
        "",
        f"**Размер:** {len(d)} строк × {d.shape[1]} столбцов. **Гранулярность строки:** (область, район, культура, год). "
        f"**Районов и городов:** {d.groupby(['region', 'district_key']).ngroups} "
        f"(из них с координатами, климатом и почвой: {d.dropna(subset=['lat']).groupby(['region', 'district_key']).ngroups}).",
        "",
        "## Как использовать для моделей",
        "",
        "- Моделируйте строки с `is_group == 0` и известной `yield_kgha`; для `area_ha` как признака добавьте `area_suspect == 0`.",
        "- Строки года соседних районов коррелированы (общая погода и рынок): кроме обычного K-fold, проверяйте модель "
        "разбиением по годам.",
        "- Региональные цены (`price_*_kzt_t`) есть только за 2022–2025; до 2022 года они пустые. Готовое подмножество — "
        "`master_dataset_districts_2022_2025.csv`.",
        "- Цены сезона уборки года Y известны только после посева года Y; для прогноза «на момент посева» берите `*_lag1_*`.",
        "",
        "Пропуски в большинстве столбцов не случайны и объяснены в README (раздел «Районный master-датасет»).",
        "",
    ]
    for group, src, cols in GROUPS:
        lines += [f"## {group}", "", f"Источник/скрипт: {src}", "",
                  "| Столбец | Единица | Описание | Пропуски | Диапазон |", "|---|---|---|---|---|"]
        for col, (unit, text) in cols.items():
            s = d[col]
            lines.append(f"| `{col}` | {unit} | {text} | {s.isna().mean():.1%} | {fmt_range(s)} |")
        lines.append("")
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Словарь: {d.shape[1]} столбцов -> {OUT_PATH}")


if __name__ == "__main__":
    main()
